const Database=require('better-sqlite3')
const {readFileSync}=require('node:fs')
const {resolve,sep}=require('node:path')
const {tmpdir}=require('node:os')
const [path,file]=process.argv.slice(2)
if(!resolve(path).startsWith(resolve(tmpdir())+sep)||!resolve(file).startsWith(resolve(tmpdir())+sep))throw Error('Fixture must stay in a temporary test directory')
const game=JSON.parse(readFileSync(file,'utf8'))
const db=new Database(path,{fileMustExist:true})
db.prepare('INSERT OR REPLACE INTO meta VALUES (?,?)').run('game-v2',JSON.stringify(game))
db.close()
